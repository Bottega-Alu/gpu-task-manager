_TABLES = {"it": _IT, "pt-BR": _PT_BR, "fr": _FR, "es": _ES, "de": _DE, "uk": _UK}
_lang = "en"

# (locale prefix, UI code). Russian UI falls back to Ukrainian (no Russian translation or list entry).
_PREFIXES = (("it", "it"), ("pt", "pt-BR"), ("fr", "fr"), ("es", "es"), ("de", "de"), ("uk", "uk"),
             ("italian", "it"), ("portuguese", "pt-BR"), ("french", "fr"), ("spanish", "es"),
             ("german", "de"), ("ukrainian", "uk"), ("ru", "uk"), ("russian", "uk"))


def _code_to_language(code: str) -> str:
    """Map a Windows/C locale name ('pt_BR', 'fr_CA', 'German_Germany') to a supported code, else 'en'."""
    low = code.lower().replace("-", "_")
    for prefix, lang in _PREFIXES:
        if low == prefix or low.startswith(prefix + "_"):
            return lang
    return "en"


def system_language() -> str:
    """The Windows (or C locale) UI language when supported (it, pt-BR, fr, es, de, uk; ru maps to uk), otherwise 'en'."""
    code = ""
    if sys.platform == "win32":
        try:
            import ctypes
            lcid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            code = locale.windows_locale.get(lcid, "")
        except (AttributeError, OSError):
            code = ""
    if not code:
        code = (locale.getlocale()[0] or "")
    return _code_to_language(code)


def set_language(choice: str) -> str:
    global _lang
    _lang = choice if choice in LANGUAGE_NAMES else system_language()
    return _lang


def language() -> str:
    return _lang


def _(text: str) -> str:
    table = _TABLES.get(_lang)
    return table.get(text, text) if table else text
