"""Build metadata from src/gtm_desktop/brand.py, the single source of product identity.

    python scripts/build_meta.py json                 # brand values as JSON (read by build.ps1)
    python scripts/build_meta.py version-info OUT     # Windows VERSIONINFO resource for PyInstaller
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from gtm_desktop import brand  # noqa: E402


def values() -> dict:
    return {k: getattr(brand, k) for k in dir(brand) if k.isupper()}


def version_tuple(version: str) -> tuple[int, int, int, int]:
    parts = [int(p) for p in version.split(".")[:4] if p.isdigit()]
    return tuple((parts + [0, 0, 0, 0])[:4])  # type: ignore[return-value]


def version_info(path: Path) -> None:
    v = version_tuple(brand.APP_VERSION)
    text = f"""# UTF-8 - generated by scripts/build_meta.py, do not edit
VSVersionInfo(
  ffi=FixedFileInfo(filevers={v}, prodvers={v}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', {brand.APP_PUBLISHER!r}),
      StringStruct('FileDescription', {brand.APP_NAME!r}),
      StringStruct('FileVersion', {brand.APP_VERSION!r}),
      StringStruct('InternalName', {brand.APP_SLUG!r}),
      StringStruct('LegalCopyright', {brand.COPYRIGHT!r}),
      StringStruct('OriginalFilename', {brand.EXE_NAME!r}),
      StringStruct('ProductName', {brand.APP_NAME!r}),
      StringStruct('ProductVersion', {brand.APP_VERSION!r})])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    path.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "json"
    if cmd == "json":
        print(json.dumps(values()))
    elif cmd == "version-info":
        version_info(Path(sys.argv[2]))
    else:
        sys.exit(f"unknown command {cmd}")
